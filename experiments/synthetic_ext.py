"""Synthetic stress tests with fully specified data-generating processes (DGPs).

Base DGP (d = 8 criteria, 5 informative + 3 noise), for sample i:
    z_i ~ N(0, Sigma),  Sigma_jk = rho^|j-k|                      (Gaussian copula, AR(1) correlation rho)
    x_ij = F_j^{-1}(Phi(z_ij)),  F_j = LogNormal(0, 0.5) scaled by 10 (j+1)
    eta_i = sum_{j<5} w_j * s_j' * tanh(4 (x_ij - t_j) / sd_j)  +  gamma * g(x_i)  +  shift handled at test time
        w = (.35,.25,.20,.12,.08), s' = (+1,+1,-1,+1,-1), t_j = quantile_j(.3,.5,.6,.4,.7)
        g(x) = standardised product  ((x_0 - t_0)/sd_0) * ((x_1 - t_1)/sd_1)     (pairwise interaction)
    y_i ~ Bernoulli(sigmoid(8 (eta_i - median(eta))))
Scenarios (one factor varied, others at baseline rho=0, gamma=0, delta=0):
    S5a correlation  rho   in {0, .5, .8, .95}
    S5b interaction  gamma in {0, .25, .5, 1}
    S5c covariate shift: test z shifted by delta*1 on the informative criteria, delta in {0, .5, 1, 2}
        (labels generated by the same conditional model, so P(y|x) is unchanged: pure covariate shift)
n_train = 2000, n_test = 5000, 10 seeds. Metric: test AUC; also the share of correctly recovered directions.
"""
import os as _os
ROOT = _os.path.dirname(_os.path.dirname(_os.path.abspath(__file__)))
import json, sys, time, warnings
import numpy as np
from scipy.stats import norm, lognorm
from sklearn.metrics import roc_auc_score
sys.path.insert(0, ROOT); sys.path.insert(0, f"{ROOT}/experiments")
warnings.filterwarnings("ignore")
OUT = f"{ROOT}/results/synthetic_ext.json"
W = np.array([.35, .25, .20, .12, .08]); S = np.array([1, 1, -1, 1, -1]); Q = [.3, .5, .6, .4, .7]
D, D_INF = 8, 5
MODELS = ["BAMAKAN", "LogReg", "EBM-main", "XGB-mono", "XGBoost"]


def sample(n, rho, rng, delta=0.0):
    C = rho ** np.abs(np.subtract.outer(np.arange(D), np.arange(D)))
    Z = rng.multivariate_normal(np.zeros(D), C, n)
    Z[:, :D_INF] += delta
    return np.column_stack([lognorm(0.5).ppf(norm.cdf(Z[:, j])) * 10 * (j + 1) for j in range(D)])


def label(X, ref, gamma, rng):
    """ref: (t, sd, median) fixed on a large reference sample from the baseline distribution."""
    t, sd, med = ref
    U = (X[:, :D_INF] - t) / sd
    eta = (W * S * np.tanh(4 * U)).sum(1) + gamma * U[:, 0] * U[:, 1]
    return (rng.rand(len(X)) < 1 / (1 + np.exp(-8 * (eta - med)))).astype(int)


def reference(rho, gamma):
    r = np.random.RandomState(12345)
    X = sample(200000, rho, r)
    t = np.array([np.quantile(X[:, j], q) for j, q in enumerate(Q)]); sd = X[:, :D_INF].std(0)
    U = (X[:, :D_INF] - t) / sd
    eta = (W * S * np.tanh(4 * U)).sum(1) + gamma * U[:, 0] * U[:, 1]
    return t, sd, np.median(eta)


def run():
    from benchmark import make_models
    grid = [("S5a", dict(rho=r, gamma=0, delta=0)) for r in (0, .5, .8, .95)] + \
           [("S5b", dict(rho=0, gamma=g, delta=0)) for g in (.25, .5, 1)] + \
           [("S5c", dict(rho=0, gamma=0, delta=dl)) for dl in (.5, 1, 2)]
    rows = json.load(open(OUT)) if _os.path.exists(OUT) else []
    done = {(r["scenario"], r["rho"], r["gamma"], r["delta"], r["seed"]) for r in rows}
    for sc, p in grid:
        ref = reference(p["rho"], p["gamma"])
        for seed in range(10):
            if (sc, p["rho"], p["gamma"], p["delta"], seed) in done:
                continue
            rng = np.random.RandomState(seed)
            Xtr = sample(2000, p["rho"], rng); ytr = label(Xtr, ref, p["gamma"], rng)
            Xte = sample(5000, p["rho"], rng, p["delta"]); yte = label(Xte, ref, p["gamma"], rng)
            mk = make_models("binary", seed)
            for mn in MODELS:
                t0 = time.time()
                m = mk[mn]().fit(Xtr, ytr)
                r = dict(scenario=sc, seed=seed, model=mn, auc=roc_auc_score(yte, m.predict_proba(Xte)[:, 1]),
                         fit_s=time.time() - t0, **p)
                if mn == "BAMAKAN":
                    s = m.net_.s_full().detach().numpy()[0, :D_INF, 0]
                    r["dir_recovered"] = float(np.mean((s > .5) == (S > 0)))
                rows.append(r)
            json.dump(rows, open(OUT, "w"))
            print(sc, p, "seed", seed, "done", flush=True)
    print("SYNTH_DONE", flush=True)


if __name__ == "__main__":
    run()
